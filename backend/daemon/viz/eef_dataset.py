"""The EEF marks of a registered dataset's episode, from its declaration (design doc 25 §5.1, §5.3, D85; C4 ``EefOverlay``).

The full visualizer draws what the raw data and the dataset declaration give - the declared point, fingers and axes
and the past trail; no observation, residual or model opinion (those belong to a task, in the mini player). The
episode's trajectory is had as the EEF module has it, never from an upload (design doc 25 §4.1, items 2-3): a robot
arm's pose record generated by the declaration (LeRobot, mcap), a handheld gripper's raw mcap derived episode by
episode; a raw UMI session, a handheld gripper's LeRobot export and a dataset's own ``trajectory.json`` are read
whole. The bundle is made once on the Daemon's build pool and kept in the viz disk cache under the registration,
its fingerprint and its declaration's version (``eef/<digest>/``): the first request answers 202 while it is made,
the layers are computed per request from the kept bundle. After a registration's preflight the first episodes are
made ahead (:func:`warm`).

A task given a ``trajectory.json`` that overrides the one its declaration generates gets the record's own marks in
its mini player too (:func:`record_layers`, §5.3): the TCP's past trail and three axes from the dataset's record,
each with its own calibration, dashed - the distance between the two drawings is the whole difference.
"""
from __future__ import annotations

import contextlib
import json
import logging
import os
import shutil
import tempfile
import threading
from pathlib import Path

from ..errors import ApiError
from ..results.files import LRU
from .media import digest, pending_body
from .source import Access

log = logging.getLogger("daemon.viz")

GENERATE_MESSAGE = "轨迹生成中"
#: episodes made ahead after a registration's preflight (design doc 25 §10)
WARM_EPISODES = 3
#: the layers of the record's own drawing (§5.3): its TCP's past trail and three axes
RECORD_LAYERS = ("trail_past", "point", "axis_x", "axis_y", "axis_z")
RECORD_DASH = [6, 4]

_CACHE = LRU(max_items=32, max_bytes=64 << 20)
_BINDS: dict[str, int] = {}
_BIND_LOCK = threading.Lock()
_RECORD_LOCK = threading.Lock()


# ---------------------------------------------------------------- where the trajectory comes from
def plan_of(svc, ds) -> dict:
    """``{"kind", "format", "whole", "decl", "sources", "cameras", "missing", "hh"}`` of a registration: how its
    trajectory is had (``derive`` kinds), the confirmed declaration that says so, the camera sources and their
    states (drawable, why not)."""
    from curation.extensions.eef_consistency import derive

    from .declaration import _trajectory, cameras_of, for_cli, format_of

    decl = for_cli(ds.viz_mapping)
    fmt = format_of(ds)
    sources = [c["source"] for c in cameras_of(svc, ds, decl)]
    got = _trajectory(svc, ds, decl, False, sources)
    if decl is None and got["kind"] in (derive.MISSING_POSE, derive.MISSING_DECLARATION):
        # nothing confirmed: what the registration's preflight made of a draft says what is missing
        entry = next((m for m in (ds.preflight or {}).get("modules") or []
                      if isinstance(m, dict) and m.get("id") == "eef_video_consistency"), None) \
            if isinstance(ds.preflight, dict) else None
        seen = (entry or {}).get("trajectory_source") or {}
        if seen.get("kind") in (derive.MISSING_POSE, derive.MISSING_DECLARATION):
            got = {**got, "kind": seen["kind"], "missing": seen.get("missing") or []}
    kind = got["kind"]
    whole = kind in (derive.SESSION, derive.DATASET_FILE) or (kind == derive.GENERATE and "cameras" not in got)
    hh = (((decl or {}).get("calibration") or {}).get("handheld") or {}).get("calibration")
    return {"kind": kind, "format": fmt, "whole": whole, "decl": decl, "sources": sources,
            "cameras": got.get("cameras") or [], "missing": got.get("missing") or [], "hh": hh}


def _unavailable(plan: dict) -> list[dict]:
    """The dataset's cameras nothing is drawn on, and why (the declaration's view; a handheld recording's hands
    say theirs per episode)."""
    return [{"source": c.get("source"), "camera_id": c.get("camera_id"), "reason": c.get("reason")}
            for c in plan["cameras"] if not c.get("drawable")]


@contextlib.contextmanager
def _bound(src, storage):
    """A TOS mcap dataset's episodes read by ranged GETs while the generator reads them (``streams.objects``,
    bound by dataset URI for the whole process - counted, so two builds on one dataset do not unbind each other)."""
    if src.is_local:
        yield
        return
    from curation.cli.containers import TosObjects
    from curation.streams import objects

    listing = src.listing() or storage.list()
    with _BIND_LOCK:
        if not _BINDS.get(src.uri):
            objects.bind(src.uri, TosObjects(storage, dict(listing)))
        _BINDS[src.uri] = _BINDS.get(src.uri, 0) + 1
    try:
        yield
    finally:
        with _BIND_LOCK:
            _BINDS[src.uri] -= 1
            if not _BINDS[src.uri]:
                _BINDS.pop(src.uri, None)
                objects.unbind(src.uri)


def _write(out: Path, data: bytes) -> None:
    part = out.with_name(out.name + ".part")
    part.write_bytes(data)
    os.replace(part, out)


def make_bundle(svc, src, plan: dict, index: int | None, out: Path, *, version: int | None = None) -> None:
    """Write the trajectory bundle of episode ``index`` (the whole dataset's when ``plan["whole"]``) to ``out``;
    an episode that cannot have one is ``{"unsupported": its trajectory_source}``."""
    from curation.extensions.eef_consistency import declared, derive, derive_mcap

    name = os.path.basename(str(src.uri).rstrip("/")) or src.name
    with tempfile.TemporaryDirectory(prefix="eef-overlay-") as tmp, Access(svc.rt, src).storage() as st:
        listing = src.listing()
        keys = list(listing) if listing is not None else list(st.list())
        if plan["whole"]:
            _write(out, derive._bytes(st, keys))
            return
        decl, sources = plan["decl"], plan["sources"]
        if plan["format"] == "mcap":
            numbering = {ep: f for ep, (f, _) in svc.mcap.files(src).items()}
            root = str(Access(svc.rt, src).local_root()) if src.is_local else src.uri
            with _bound(src, st):
                if plan["kind"] == derive.MCAP_DERIVE:
                    gen = derive_mcap.Derived(root=root, numbering=numbering, calibration=None, out_dir=tmp,
                                              dataset_id=name, calibration_doc=plan["hh"])
                else:
                    gen = declared.GeneratedMcap(decl, root=root, numbering=numbering, out_dir=tmp, dataset_id=name,
                                                 cameras=sources, sizes=_sizes(svc, src, decl), version=version)
                sample, source = gen.sample(int(index))
        else:
            gen = declared.Generated(decl, storage=st, listing=keys, out_dir=tmp, dataset_id=name, cameras=sources,
                                     sizes=_sizes(svc, src, decl), version=version)
            try:
                sample, source = gen.sample(int(index))
            finally:
                gen.close()
        if sample is None:
            _write(out, json.dumps({"unsupported": source}, ensure_ascii=False).encode())
        else:
            _write(out, Path(derive_mcap.bundle_path(tmp, int(index))).read_bytes())


def _sizes(svc, src, decl: dict | None) -> dict:
    """The cameras' video sizes the generators scale the intrinsics with (``facts_of``)."""
    from .declaration import facts_of

    try:
        ds = svc.rt.repo.get_dataset(src.dataset_id or src.id, owner=src.owner)
        return dict(facts_of(svc, ds, decl).cameras)
    except Exception:  # noqa: BLE001 - the generators then take the declaration's own sizes
        return {}


def _path(svc, src, ds, plan: dict, index: int) -> Path:
    key = digest(src.scope, src.id, src.fingerprint, int(ds.viz_mapping_version or 0), plan["kind"])
    return svc.disk.path("eef", key, "bundle.json" if plan["whole"] else f"ep{int(index):06d}.json")


def ensure(svc, src, ds, plan: dict, index: int):
    """The job making episode ``index``'s bundle (done at once when it is kept), and its layers at the viewer's
    default gap, so that the first look draws at once."""
    from .eef_overlay import overlay_cameras

    out = _path(svc, src, ds, plan, index)
    version = int(ds.viz_mapping_version or 0)

    def make(progress) -> None:
        make_bundle(svc, src, plan, None if plan["whole"] else index, out, version=version)
        if _unsupported(out) is None:
            try:
                overlay_cameras(out, int(index), cache=_CACHE, scope=("dataset", ds.id), kept=True)
            except ApiError:                      # the request says why
                pass

    return svc.builder.ensure(f"eef:{out}", out, make, message=GENERATE_MESSAGE)


def warm(svc, ds, episodes: list[int]) -> None:
    """Make the first episodes' bundles ahead, on the build pool (design doc 25 §5.1); never raises."""
    try:
        from curation.extensions.eef_consistency import derive

        src = svc.dataset_source(ds.id, ds.owner_id)
        plan = plan_of(svc, ds)
        if plan["kind"] in (derive.MISSING_POSE, derive.MISSING_DECLARATION) or plan["format"] not in (
                "lerobot", "mcap", "umi_session"):
            return
        for ep in (episodes[:1] if plan["whole"] else episodes[:WARM_EPISODES]):
            ensure(svc, src, ds, plan, int(ep))
    except Exception:  # noqa: BLE001 - only a head start: the first request makes it all the same
        log.warning("eef overlay: could not make %s's first episodes ahead", ds.id, exc_info=True)


# ---------------------------------------------------------------- the overlay
#: an episode that cannot have a trajectory is kept as a small stub (``{"unsupported": ...}``); a bundle is larger
_STUB_BYTES = 64 << 10


def _unsupported(path: Path) -> dict | None:
    """The trajectory_source of an episode kept as one that cannot have a trajectory, else None."""
    try:
        if path.stat().st_size > _STUB_BYTES:
            return None
        head = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    return (head["unsupported"] or {}) if isinstance(head, dict) and "unsupported" in head else None


def _why(source: dict) -> str:
    """Why an episode has no trajectory, in words: the generator's message, else each camera's reason (a handheld
    recording's hands), else the code."""
    if source.get("message"):
        return str(source["message"])
    said = [f"{k}：{c['reason']}" for k, c in sorted((source.get("cameras") or {}).items())
            if isinstance(c, dict) and c.get("reason")]
    return "；".join(said) or str(source.get("reason") or "")


def dataset_overlay(rt, svc, dataset_id: str, owner: str, index: int, *, max_gap_ms: float | None = None):
    """C4 ``EefOverlay`` of a registration's episode, or the 202 of its bundle still being made."""
    from starlette.responses import JSONResponse

    from curation.extensions.eef_consistency import derive

    from .eef_overlay import camera_maps, overlay_cameras

    ds = rt.repo.get_dataset(dataset_id, owner=owner)
    src = svc.dataset_source(dataset_id, owner)
    plan = plan_of(svc, ds)
    if plan["format"] not in ("lerobot", "mcap", "umi_session"):
        raise ApiError("not_found", "这种格式的数据集还不能画轨迹叠加", details={"reason": "format_not_generated"})
    if plan["kind"] in (derive.MISSING_POSE, derive.MISSING_DECLARATION):
        raise ApiError("not_found", "平台还得不到这个数据集的轨迹：数据集声明还缺几项，或数据集没有位姿记录",
                       details={"reason": "no_trajectory", "kind": plan["kind"], "missing": plan["missing"]})
    dataset = (ds.preflight or {}).get("dataset") if isinstance(ds.preflight, dict) else None
    if isinstance(dataset, dict):
        from curation.planner import PlanError, dataset_episodes

        try:
            known = set(dataset_episodes(dataset))
        except PlanError:
            known = None
        if known is not None and int(index) not in known:
            raise ApiError("not_found", f"数据集里没有 episode {index}", details={"reason": "no_episode"})
    job = ensure(svc, src, ds, plan, int(index))
    if job.state == "failed":
        raise ApiError("internal", f"轨迹生成失败：{job.message}", details={"reason": "generate_failed"})
    if job.state != "done":
        return JSONResponse(pending_body(job), status_code=202, headers={"Cache-Control": "no-store"})
    path = Path(job.out)
    source = _unsupported(path) if not plan["whole"] else None
    if source is not None:
        raise ApiError("not_found", f"episode {index} 生成不出轨迹：{_why(source)}",
                       details={"reason": "not_generated", "source": source})
    cameras, bridged = overlay_cameras(path, int(index), max_gap_ms=max_gap_ms, cache=_CACHE, scope=("dataset", ds.id),
                                       kept=True)
    for c in cameras:                       # no task, no model: nothing here was shown to one
        for layer in c["layers"]:
            layer["in_model"], layer["model_color"] = False, None
    files, topics, times = camera_maps(svc, src, int(index))
    out = []
    for c in cameras:
        viz = topics.get(c["topic"]) if c["topic"] else files.get(c["media_uri"])
        frames = c["media_frames"]
        out.append({k: v for k, v in c.items() if k not in ("media_uri", "topic")}
                   | {"viz_camera": viz, "times_s": times(viz, frames) if viz and times else [None] * len(frames)})
    shown = {c["viz_camera"] for c in out if c["viz_camera"]}
    viz_by_source = {}
    try:
        viz_by_source = {c["source"]: c["key"] for c in svc.dataset(src).get("cameras") or [] if c.get("source")}
    except Exception:  # noqa: BLE001 - the reasons still come back, without their player camera
        pass
    unavailable = [{**u, "viz_camera": viz_by_source.get(u["source"])} for u in _unavailable(plan)
                   if viz_by_source.get(u["source"]) not in shown]
    return {"task_id": None, "dataset_id": ds.id, "episode_index": int(index), "cameras": out,
            "interpolation": bridged, "unavailable_cameras": unavailable,
            "trajectory": {"kind": plan["kind"], "declaration_version": int(ds.viz_mapping_version or 0) or None}}


# ---------------------------------------------------------------- the record's own drawing (§5.3)
def record_layers(rt, svc, task, src, index: int) -> dict[str, list[dict]]:
    """``{media uri or topic: layers}`` - the dataset record's TCP trail and axes for a task whose uploaded
    trajectory overrides the one its frozen declaration generates (design doc 25 §5.3, D85); empty when the
    declaration generates none or the episode cannot have one. Made on request, kept beside the bundles."""
    from curation import declaration as DCL
    from curation.extensions.eef_consistency import declared, load, overlay

    from ..results.store import store_of

    path = store_of(rt).task_dir(task.id) / "inputs" / "declaration.json"
    try:
        decl = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    decl = decl.get("document", decl) if isinstance(decl, dict) else None
    if not isinstance(decl, dict):
        return {}
    fmt = str(((src.preflight or {}).get("format") or {}).get("kind") or "")
    if fmt not in ("lerobot", "mcap"):
        return {}
    sources = list((decl.get("calibration") or {}).get("cameras") or {})
    if not declared.readiness(decl, sources, kind=fmt)["ready"]:
        return {}
    plan = {"kind": "generate", "format": fmt, "whole": False, "decl": decl, "sources": sources, "cameras": [],
            "missing": [], "hh": None}
    out = svc.disk.path("eef-record", digest(task.id, DCL.sha256(decl), src.fingerprint), f"ep{int(index):06d}.json")
    with _RECORD_LOCK:
        if svc.disk.get(out) is None:
            try:
                make_bundle(svc, src, plan, int(index), out)
                svc.disk.added(out)
            except Exception:  # noqa: BLE001 - the task's own marks still come back
                log.warning("eef overlay: the record of task %s episode %s could not be drawn", task.id, index,
                            exc_info=True)
                return {}
    if _unsupported(out) is not None:
        return {}
    try:
        stat = out.stat()
    except OSError:
        return {}
    key = ("record", str(out), stat.st_ino, stat.st_size, int(index))   # read through the disk cache: its inode tells
    hit = _CACHE.get(key)
    if hit is not None:
        return json.loads(json.dumps(hit))
    result = load.load_bundle(out, check_media=False, episodes=[int(index)], trusted=True)
    sample = result.samples.get(int(index)) if result.ok else None
    if sample is None:
        return {}
    got: dict[str, list[dict]] = {}
    for c in overlay.episode_overlay(sample):
        media = sample.cameras[c["camera_id"]].media
        where = media.get("topic") or media.get("uri")
        layers = []
        for layer in c["layers"]:
            if layer["id"] not in RECORD_LAYERS:
                continue
            layers.append({**layer, "id": f"record_{layer['id']}", "group": "record",
                           "title": f"记录 · {layer['title']}", "dash": list(RECORD_DASH), "in_model": False,
                           "model_color": None})
        if layers and where:
            got[where] = layers
    _CACHE.put(key, got, len(json.dumps(got)))
    return json.loads(json.dumps(got))
